#include <stdint.h>
#include <wolfHAL/wolfHAL.h>
#include "board.h"
#include "test.h"

/* RFC 2202 / RFC 4231 Test Case 1: HMAC with 20-byte 0x0b key, "Hi There" */
static const uint8_t hmacKey[20] = {
    0x0B, 0x0B, 0x0B, 0x0B, 0x0B, 0x0B, 0x0B, 0x0B,
    0x0B, 0x0B, 0x0B, 0x0B, 0x0B, 0x0B, 0x0B, 0x0B,
    0x0B, 0x0B, 0x0B, 0x0B,
};

static const uint8_t hmacInput[] = {
    'H', 'i', ' ', 'T', 'h', 'e', 'r', 'e',
};

/* RFC 4231 section 4, Test Case 1 */
static const uint8_t hmacSha224Digest[28] = {
    0x89, 0x6F, 0xB1, 0x12, 0x8A, 0xBB, 0xDF, 0x19,
    0x68, 0x32, 0x10, 0x7C, 0xD4, 0x9D, 0xF3, 0x3F,
    0x47, 0xB4, 0xB1, 0x16, 0x99, 0x12, 0xBA, 0x4F,
    0x53, 0x68, 0x4B, 0x22,
};

static void Test_HmacSha224_KnownAnswer(void)
{
    uint8_t digest[28] = {0};

    WHAL_ASSERT_EQ(whal_HmacSha224_Oneshot(BOARD_HMAC_SHA224_DEV,
                                           hmacKey, sizeof(hmacKey),
                                           hmacInput, sizeof(hmacInput),
                                           digest, sizeof(digest)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(digest, hmacSha224Digest, sizeof(hmacSha224Digest));
}

/* Streaming KAT: 100-byte message split mid-block, same hmacKey as above.
 * Vectors generated by tests/crypto/gen_test_vectors.py. */
static const uint8_t hmacStreamMsg[100] = {
    0x03, 0x0A, 0x11, 0x18, 0x1F, 0x26, 0x2D, 0x34,
    0x3B, 0x42, 0x49, 0x50, 0x57, 0x5E, 0x65, 0x6C,
    0x73, 0x7A, 0x81, 0x88, 0x8F, 0x96, 0x9D, 0xA4,
    0xAB, 0xB2, 0xB9, 0xC0, 0xC7, 0xCE, 0xD5, 0xDC,
    0xE3, 0xEA, 0xF1, 0xF8, 0xFF, 0x06, 0x0D, 0x14,
    0x1B, 0x22, 0x29, 0x30, 0x37, 0x3E, 0x45, 0x4C,
    0x53, 0x5A, 0x61, 0x68, 0x6F, 0x76, 0x7D, 0x84,
    0x8B, 0x92, 0x99, 0xA0, 0xA7, 0xAE, 0xB5, 0xBC,
    0xC3, 0xCA, 0xD1, 0xD8, 0xDF, 0xE6, 0xED, 0xF4,
    0xFB, 0x02, 0x09, 0x10, 0x17, 0x1E, 0x25, 0x2C,
    0x33, 0x3A, 0x41, 0x48, 0x4F, 0x56, 0x5D, 0x64,
    0x6B, 0x72, 0x79, 0x80, 0x87, 0x8E, 0x95, 0x9C,
    0xA3, 0xAA, 0xB1, 0xB8,
};

static const uint8_t hmacSha224StreamMac[28] = {
    0x15, 0xED, 0x14, 0xD1, 0x5C, 0x32, 0x35, 0x44,
    0x0A, 0x42, 0x10, 0x73, 0x17, 0x2B, 0x42, 0x93,
    0xD8, 0xFF, 0x04, 0x4F, 0x5F, 0x08, 0x33, 0x14,
    0xB0, 0x34, 0x5A, 0x95,
};

static void Test_HmacSha224_Streaming(void)
{
    uint8_t digest[28] = {0};
    const size_t split = 50;

    WHAL_ASSERT_EQ(whal_HmacSha224_Start(BOARD_HMAC_SHA224_DEV,
                                         hmacKey, sizeof(hmacKey)),
                   WHAL_SUCCESS);
    WHAL_ASSERT_EQ(whal_HmacSha224_Process(BOARD_HMAC_SHA224_DEV,
                                           hmacStreamMsg, split),
                   WHAL_SUCCESS);
    WHAL_ASSERT_EQ(whal_HmacSha224_Process(BOARD_HMAC_SHA224_DEV,
                                           hmacStreamMsg + split,
                                           sizeof(hmacStreamMsg) - split),
                   WHAL_SUCCESS);
    WHAL_ASSERT_EQ(whal_HmacSha224_Finalize(BOARD_HMAC_SHA224_DEV,
                                            digest, sizeof(digest)),
                   WHAL_SUCCESS);

    WHAL_ASSERT_MEM_EQ(digest, hmacSha224StreamMac, sizeof(hmacSha224StreamMac));
}

void whal_Test_HmacSha224(void)
{
    WHAL_TEST_SUITE_START("hmac_sha224");
    WHAL_TEST(Test_HmacSha224_KnownAnswer);
    WHAL_TEST(Test_HmacSha224_Streaming);
    WHAL_TEST_SUITE_END();
}
